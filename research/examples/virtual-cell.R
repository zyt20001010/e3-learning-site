set.seed(20261126)
initial <- c(A=60,B=60)
transition <- matrix(c(0.5,0,0.5,1),nrow=2,byrow=TRUE)
selection <- diag(c(1/3,1))
converted <- as.vector(transition %*% initial)
selected <- as.vector(selection %*% initial)
normalize <- function(x) x/sum(x)
p_conversion <- normalize(converted)
p_selection <- normalize(selected)
stopifnot(all(converted==c(30,90)),all(selected==c(20,60)))
stopifnot(max(abs(p_conversion-p_selection))<1e-12)
expression <- rbind(A=c(2,0),B=c(0,2))
mean_conversion <- as.vector(p_conversion %*% expression)
mean_selection <- as.vector(p_selection %*% expression)
stopifnot(max(abs(mean_conversion-c(0.5,1.5)))<1e-12)
stopifnot(max(abs(mean_conversion-mean_selection))<1e-12)
m <- 20L
pmf_conversion <- dbinom(0:m,size=m,prob=p_conversion[1])
pmf_selection <- dbinom(0:m,size=m,prob=p_selection[1])
stopifnot(max(abs(pmf_conversion-pmf_selection))<1e-12)
stopifnot(sum(converted)==120,sum(selected)==80)
print(rbind(conversion=converted,selection=selected))
print(rbind(p_conversion=p_conversion,p_selection=p_selection))
print(c(gene1=mean_conversion[1],gene2=mean_conversion[2],
        total_conversion=sum(converted),total_selection=sum(selected)))
